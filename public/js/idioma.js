// Idioma por defecto
let idiomaActual = localStorage.getItem('idioma') || 'es';

// Cambiar idioma
function cambiarIdioma(nuevoIdioma) {
  if (traducciones[nuevoIdioma]) {
    idiomaActual = nuevoIdioma;
    localStorage.setItem('idioma', nuevoIdioma);
    aplicarTraducciones();
  }
}

// Aplicar traducciones a todos los elementos
function aplicarTraducciones() {
  const elementos = document.querySelectorAll('[data-txt]');
  elementos.forEach(el => {
    const clave = el.getAttribute('data-txt');
    if (traducciones[idiomaActual] && traducciones[idiomaActual][clave]) {
      el.textContent = traducciones[idiomaActual][clave];
    }
  });
  
  // Placeholders
  const placeholders = document.querySelectorAll('[data-txt-placeholder]');
  placeholders.forEach(el => {
    const clave = el.getAttribute('data-txt-placeholder');
    if (traducciones[idiomaActual] && traducciones[idiomaActual][clave]) {
      el.placeholder = traducciones[idiomaActual][clave];
    }
  });
  
  // Actualizar moneda según idioma
  if (typeof cambiarMoneda === 'function') {
    const monedaPorIdioma = {
      es: 'UYU', en: 'USD', pt: 'BRL', zh: 'CNY', ja: 'JPY', ko: 'KRW',
      ar: 'AED', hi: 'INR', ru: 'RUB', de: 'EUR', fr: 'EUR', it: 'EUR',
      tr: 'TRY', vi: 'VND'
    };
    if (monedaPorIdioma[idiomaActual]) {
      cambiarMoneda(monedaPorIdioma[idiomaActual]);
    }
  }
}

// Obtener texto traducido
function t(clave) {
  if (traducciones[idiomaActual] && traducciones[idiomaActual][clave]) {
    return traducciones[idiomaActual][clave];
  }
  return clave;
}

// Obtener lista de idiomas disponibles
function obtenerIdiomasDisponibles() {
  return Object.keys(traducciones).map(codigo => ({
    codigo: codigo,
    nombre: {
      es: 'Español', en: 'English', zh: '中文', hi: 'हिन्दी', ar: 'العربية',
      pt: 'Português', ru: 'Русский', ja: '日本語', fr: 'Français', de: 'Deutsch',
      ko: '한국어', it: 'Italiano', tr: 'Türkçe', vi: 'Tiếng Việt'
    }[codigo]
  }));
}

// Inicializar al cargar
document.addEventListener('DOMContentLoaded', () => {
  aplicarTraducciones();
  
  const selector = document.getElementById('selector-idioma');
  if (selector) {
    selector.value = idiomaActual;
    selector.addEventListener('change', (e) => {
      cambiarIdioma(e.target.value);
    });
  }
});
